def fixture():
    target=np.random.default_rng(12).uniform(-1,1,(600,3)).astype(np.float32)
    angle=np.deg2rad(60)
    rotation=np.array([[np.cos(angle),-np.sin(angle),0],[np.sin(angle),np.cos(angle),0],[0,0,1]])
    source=(target@rotation.T+[3,-2,.5]).astype(np.float32)
    schedule=[dict(leaf=.1,max_distance=.5,iterations=30),dict(leaf=None,max_distance=.1,iterations=30)]
    return source,target,schedule


def test_global_generation_recovers_large_pose_without_input_prior(module):
    source,target,schedule=fixture()
    aligned,report=module.align_global_clouds(sr.PointCloud.from_xyz(source),sr.PointCloud.from_xyz(target),schedule)
    np.testing.assert_allclose(aligned.xyz(),target,atol=5e-5)
    assert not report['initial_transform_supplied']
    selection=report['candidate_selection']
    assert [r['seed'] for r in selection['candidates']] == [7,8,9]
    assert selection['successful_candidates'] == 3
    keys=[(r['aligned_support']['distance_gated_points'],-r['aligned_support']['gated_rmse_metres']) for r in selection['candidates']]
    assert selection['selected_index'] == max(range(3),key=lambda i:keys[i])
    from render_alignment_report import render_report
    rendered=render_report(report)
    assert 'generated by FPFH/RANSAC; no caller-supplied pose' in rendered
    assert 'default identity' not in rendered
    assert 'Seeds in candidate order: 7, 8, 9' in rendered
    report['initial_transform_supplied']=True
    with pytest.raises(ValueError,match='caller supplied'):
        render_report(report)


