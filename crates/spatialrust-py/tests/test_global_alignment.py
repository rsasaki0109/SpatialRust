def test_cli_full_source_roundtrip_and_exclusive_output(module,tmp_path):
    source,target,schedule=fixture()
    paths=[tmp_path/'source.pcd',tmp_path/'target.pcd']
    sr.write(str(paths[0]),sr.PointCloud.from_xyz(source));sr.write(str(paths[1]),sr.PointCloud.from_xyz(target))
    config=tmp_path/'schedule.json';config.write_text(json.dumps(schedule))
    output=tmp_path/'aligned'
    command=[sys.executable,str(EXAMPLES/'align_global.py'),*map(str,paths),'--schedule',str(config),'--output-dir',str(output),'--html-report']
    result=subprocess.run(command,capture_output=True,text=True,timeout=60)
    assert result.returncode==0,result.stderr
    np.testing.assert_allclose(sr.read(str(output/'aligned.pcd')).xyz(),target,atol=5e-5)
    saved=(output/'aligned.pcd').read_bytes()
    assert subprocess.run(command,capture_output=True,timeout=60).returncode!=0
    assert (output/'aligned.pcd').read_bytes()==saved


def test_global_output_preserves_typed_attributes_and_rotates_normals(module,tmp_path):
    import pyarrow as pa
    from test_alignment_attributes import write_rich_pcd
    source,target,schedule=fixture()
    normals=np.tile([0,1,0],(len(source),1)).astype(np.float32)
    path=tmp_path/'rich.pcd'
    intensity,labels,timestamps=write_rich_pcd(path,source,normals)
    original=sr.read(str(path))
    aligned,report=module.align_global_clouds(original,sr.PointCloud.from_xyz(target),schedule)
    columns=pa.array(aligned)
    assert aligned.field_names()==original.field_names()
    for name,expected in [('intensity',intensity),('label',labels),('timestamp',timestamps)]:
        np.testing.assert_array_equal(columns.field(name).to_numpy(),expected)
    actual=np.column_stack([columns.field('normal_'+axis).to_numpy() for axis in 'xyz'])
    np.testing.assert_allclose(actual,normals@np.asarray(report['transform_source_to_target'])[:3,:3].T,atol=2e-6)
    np.testing.assert_array_equal(original.xyz(),source)


