def test_failed_global_seed_is_reported_and_remaining_seed_can_succeed(module):
    source,target,schedule=fixture()
    original=sr.register_fpfh_ransac
    def attempt(*args,**kwargs):
        if kwargs['seed']==7:
            raise ValueError('controlled failed hypothesis')
        return original(*args,**kwargs)
    with patch.object(sr,'register_fpfh_ransac',side_effect=attempt):
        _,report=module.align_global_clouds(sr.PointCloud.from_xyz(source),sr.PointCloud.from_xyz(target),schedule,seeds=[7,8])
    records=report['candidate_selection']['candidates']
    assert records[0]['status']=='error'
    assert records[0]['error']=='controlled failed hypothesis'
    assert report['candidate_selection']['selected_index']==1
    from render_alignment_report import render_report
    assert 'controlled failed hypothesis' in render_report(report)


